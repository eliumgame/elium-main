/**
 * The « Modifier le texte » engine on a corpus of real-world PDFs
 * (tests/fixtures/textedit, regenerated by tests/support/textedit-fixtures.*):
 * LibreOffice (Word / PowerPoint), pdf-lib (Standard 14, CID), Chromium, a
 * Form XObject. Every detected paragraph of every page is edited.
 */

const FIXTURES = ["letter", "slides", "form-xobject", "pdflib", "chromium"] as const;
const bytesOf = (name: string) => new Uint8Array(readFileSync(`tests/fixtures/textedit/${name}.pdf`));

const sources = new Map<string, { bytes: Uint8Array; engine: PdfEngine }>();
async function open(name: string) {
  let s = sources.get(name);
  if (!s) {
    const bytes = bytesOf(name);
    s = { bytes, engine: await PdfEngine.open(bytes.slice()) };
    sources.set(name, s);
  }
  return s;
}

async function blocksOf(name: string, page: number): Promise<TextBlock[]> {
  const { bytes, engine } = await open(name);
  return readTextBlocks(engine, { bytes }, page);
}

/** pdf.js' view of a one-page PDF: its lines and its whole text. */
async function lookAt(bytes: Uint8Array): Promise<{ lines: TextLine[]; text: string; blocks: TextBlock[] }> {
  const engine = await PdfEngine.open(bytes.slice());
  const page = await engine.page(0);
  const vp = page.getViewport({ scale: 1, rotation: 0 });
  const [tc, fonts] = await Promise.all([engine.text(0), engine.fonts(0)]);
  const lines = groupLines(buildRuns(tc, vp.transform as unknown as number[], fonts), tc.items);
  const blocks = await readTextBlocks(engine, { bytes }, 0);
  const text = (tc.items as { str?: string }[]).map((i) => i.str ?? "").join("");
  return { lines, text, blocks };
}

const NORM = (s: string) => s.normalize("NFKC").replace(/\s+/g, "");
const flat = (s: string) => s.replace(/\s+/g, " ").trim();

/** Characters of `a` minus those of `b` (a multiset difference), sorted, as a string. */
function bag(s: string): Map<string, number> {
  const m = new Map<string, number>();
  for (const ch of NORM(s)) m.set(ch, (m.get(ch) ?? 0) + 1);
  return m;
}
function sameBag(a: Map<string, number>, b: Map<string, number>): string[] {
  const diff: string[] = [];
  for (const k of new Set([...a.keys(), ...b.keys()])) {
    const d = (a.get(k) ?? 0) - (b.get(k) ?? 0);
    if (d) diff.push(`${k}:${d > 0 ? "+" : ""}${d}`);
  }
  return diff;
}

function editOf(b: TextBlock, spans: TextSpan[], extra: Partial<ContentEdit> = {}): ContentEdit {
  return {
    id: `e-${b.key}`,
    pageId: "p",
    blockKey: b.key,
    original: b.text,
    text: spans.map((s) => s.text).join(""),
    rect: b.rect,
    fontSize: b.fontSize,
    leading: b.leading,
    align: b.align,
    fontFamily: b.fontFamily,
    bold: b.bold,
    italic: b.italic,
    spans,
    indent: b.indent,
    ...extra,
  };
}

/** The block with " AJOUT" typed at its end (in the style of its last span). */
function appended(b: TextBlock): TextSpan[] {
  const spans = b.spans!.map((s) => ({ ...s }));
  spans[spans.length - 1] = { ...spans[spans.length - 1], text: spans[spans.length - 1].text + " AJOUT" };
  return spans;
}

/** The block with its longest word (≥ 4 letters, in a span of its own style) replaced by « REMPLACÉ ». */
function changed(b: TextBlock): { spans: TextSpan[]; word: string } | null {
  let best: { si: number; word: string; at: number } | null = null;
  b.spans!.forEach((s, si) => {
    const re = /\p{L}{4,}/gu;
    let m: RegExpExecArray | null;
    while ((m = re.exec(s.text)) !== null)
      if (!best || m[0].length > best.word.length) best = { si, word: m[0], at: m.index };
  });
  if (!best) return null;
  const { si, word, at } = best as { si: number; word: string; at: number };
  const spans = b.spans!.map((s) => ({ ...s }));
  spans[si] = { ...spans[si], text: spans[si].text.slice(0, at) + "REMPLACÉ" + spans[si].text.slice(at + word.length) };
  return { spans, word };
}

