describe("text edit engine — editing every block of the corpus", () => {
  for (const name of FIXTURES) {
    it(`${name}: append a word / change a word, nothing else moves, nothing doubles`, async () => {
      const { bytes, engine } = await open(name);
      for (let p = 0; p < engine.pageCount; p++) {
        const blocks = await blocksOf(name, p);
        const before = await lookAt((await rewrittenPage(bytes, null, p, [])).bytes);
        for (const b of blocks) {
          // A column of bullets alone (no letter, no digit) is not edited as text.
          if (!/[\p{L}\p{N}]/u.test(b.text)) continue;
          const variants: { spans: TextSpan[]; label: string }[] = [{ spans: appended(b), label: "append" }];
          const c = changed(b);
          if (c) variants.push({ spans: c.spans, label: `change ${c.word}` });
          for (const v of variants) {
            const edit = editOf(b, v.spans);
            const r = await rewrittenPage(bytes, null, p, [edit]);
            const where = `${name} p${p} ${b.key} ${v.label}`;
            expect(r.skipped, where).toBe(0);
            const after = await lookAt(r.bytes);
            // Exactly the original's characters out, the new ones in.
            const expected = bag(before.text);
            for (const [k, n] of bag(b.text)) expected.set(k, (expected.get(k) ?? 0) - n);
            for (const [k, n] of bag(edit.text)) expected.set(k, (expected.get(k) ?? 0) + n);
            expect(sameBag(bag(after.text), expected), where).toEqual([]);
            expect(NORM(after.text), where).toContain(NORM(edit.text).slice(-12));
            // Every other paragraph is still there, word for word.
            const out = new Set(after.blocks.map((x) => NORM(x.text)));
            const outAll = NORM(after.blocks.map((x) => x.text).join(""));
            // (Text a longer paragraph grows over — the two lines under it — may mix with it in pdf.js'
            // reading: the character count above already proves nothing was lost or doubled there.)
            const grow = {
              x0: b.rect.x,
              x1: b.rect.x + b.rect.w,
              y0: b.rect.y,
              y1: b.rect.y + b.rect.h + 2.2 * b.leading,
            };
            for (const o of blocks) {
              if (o === b || !NORM(o.text)) continue;
              const inBand =
                o.rect.x < grow.x1 &&
                o.rect.x + o.rect.w > grow.x0 &&
                o.rect.y < grow.y1 &&
                o.rect.y + o.rect.h > grow.y0;
              if (inBand) continue;
              if (!out.has(NORM(o.text)))
                expect(outAll, `${where}: ${o.key} « ${flat(o.text)} »`).toContain(NORM(o.text));
            }
          }
        }
      }
    }, 120_000);
  }
});

describe("text edit engine — fidelity", () => {
  it("re-laying out an unchanged paragraph puts back its line breaks and baselines (±1.5 pt)", async () => {
    let checked = 0;
    for (const name of FIXTURES) {
      const { bytes, engine } = await open(name);
      for (let p = 0; p < engine.pageCount; p++) {
        for (const b of await blocksOf(name, p)) {
          if (!/\p{L}/u.test(b.text) || Math.abs(b.lines[0].angle) > 0.01) continue;
          const r = await rewrittenPage(bytes, null, p, [editOf(b, b.spans!)]);
          const after = await lookAt(r.bytes);
          const where = `${name} p${p} ${b.key} « ${flat(b.text).slice(0, 40)} »`;
          const near = (l: TextLine) =>
            l.origin.y > b.rect.y - 2 &&
            l.origin.y < b.rect.y + b.rect.h + 2 &&
            l.rect.x > b.rect.x - 3 &&
            l.rect.x < b.rect.x + b.rect.w;
          const got = after.lines.filter(near);
          expect(
            got.map((l) => NORM(l.text)),
            where,
          ).toEqual(b.lines.map((l) => NORM(l.text)));
          got.forEach((l, i) => {
            const o = b.lines[i];
            expect(Math.abs(l.origin.y - o.origin.y), `${where} line ${i} baseline`).toBeLessThan(1.5);
            if (b.align === "left" || b.align === "justify")
              expect(Math.abs(l.rect.x - o.rect.x), `${where} line ${i} start`).toBeLessThan(1.5);
            if (b.align === "right" || (b.align === "justify" && b.soft?.[i]))
              expect(Math.abs(l.rect.x + l.rect.w - (o.rect.x + o.rect.w)), `${where} line ${i} end`).toBeLessThan(1.5);
          });
          checked++;
        }
      }
    }
    expect(checked).toBeGreaterThan(30);
  }, 120_000);

  it("a bold word stays bold, a red word red, when another word of the paragraph is edited", async () => {
    for (const [name, start] of [
      ["letter", "Nous attirons"],
      ["chromium", "Second paragraphe"],
    ] as const) {
      const { bytes } = await open(name);
      const b = (await blocksOf(name, 0)).find((x) => x.text.startsWith(start))!;
      const spans = b.spans!.map((s, i) => (i === 0 ? { ...s, text: s.text.replace(/^\S+/, "Désormais, nous") } : s));
      const r = await rewrittenPage(bytes, null, 0, [editOf(b, spans)]);
      const out = (await lookAt(r.bytes)).blocks.find((x) => x.text.startsWith("Désormais"))!;
      expect(out, name).toBeTruthy();
      expect(out.spans!.find((s) => s.style.bold)!.text.trim()).toBe(b.spans!.find((s) => s.style.bold)!.text.trim());
      expect(out.spans!.find((s) => s.style.color === "#c00000")!.text.trim()).toBe("rouge");
      // Still set in the paragraph's own fonts (no substitution).
      const names = new Set(out.spans!.map((s) => s.style.fontName));
      for (const s of b.spans!) expect(names.has(s.style.fontName), `${name} ${s.style.fontName}`).toBe(true);
    }
  });

  it("a word the subset font lacks is set in a substitute face, that word only", async () => {
    const { bytes } = await open("pdflib");
    const b = (await blocksOf("pdflib", 1)).find((x) => x.text.startsWith("Ce paragraphe"))!;
    const spans = [{ ...b.spans![0], text: b.spans![0].text.replace("Ce paragraphe", "Ce Ωmega paragraphe") }];
    const r = await rewrittenPage(bytes, null, 1, [editOf(b, spans)]);
    const out = (await lookAt(r.bytes)).blocks.find((x) => x.text.includes("Ωmega"))!;
    expect(out.text).toBe(spans[0].text);
    const own = out.spans!.filter((s) => s.style.fontName === b.spans![0].style.fontName);
    // Everything but the new word keeps the original CID font.
    expect(own.map((s) => s.text).join("").length).toBeGreaterThan(out.text.length - 10);
  });
});

describe("text edit engine — safety", () => {
  it("text inside a form XObject drawn by two pages: edited on one page only", async () => {
    const { PDFDocument } = await import("pdf-lib");
    const { pageFrame } = await import("../src/pdf/ops/annots-pdf");
    const { FontBook } = await import("../src/pdf/ops/fonts");
    const { applyTextEdits } = await import("../src/pdf/ops/textedit");
    const { bytes } = await open("form-xobject");
    const b = (await blocksOf("form-xobject", 0)).find((x) => x.text.startsWith("Le présent"))!;
    const doc = await PDFDocument.load(bytes);
    const page = doc.getPage(0);
    const r = await applyTextEdits(doc, page, [editOf(b, appended(b))], pageFrame(page), new FontBook(doc));
    // (« AJOUT »'s capitals are not in the subset font: that word is substituted.)
    expect(r.skipped).toBe(0);
    expect(r.native + r.substituted).toBe(1);
    const out = await doc.save();
    const all = await PdfEngine.open(out.slice());
    const text = async (i: number) =>
      ((await all.text(i)).items as { str?: string }[]).map((x) => x.str ?? "").join("");
    expect(NORM(await text(0))).toContain(NORM(b.text + " AJOUT"));
    expect(NORM(await text(0)).split(NORM("Le présent document")).length).toBe(2);
    // Page 2 draws the same form: untouched.
    expect(NORM(await text(1))).toContain(NORM(b.text));
    expect(NORM(await text(1))).not.toContain("AJOUT");
  });

  it("a block that is no longer there is skipped, and nothing is drawn", async () => {
    const { bytes } = await open("letter");
    const b = (await blocksOf("letter", 0)).find((x) => x.text.startsWith("Veuillez"))!;
    const ghost = editOf(b, [{ ...b.spans![0], text: "Texte fantôme" }], {
      original: "Un paragraphe qui n'existe pas du tout sur cette page",
    });
    const r = await rewrittenPage(bytes, null, 0, [ghost]);
    expect(r.skipped).toBe(1);
    const after = await lookAt(r.bytes);
    expect(after.text).not.toContain("fantôme");
    expect(NORM(after.text)).toContain(NORM(b.text));
    // Elsewhere on the page: nothing there at all.
    const empty = editOf(b, [{ ...b.spans![0], text: "Rien" }], { rect: { x: 300, y: 600, w: 100, h: 20 } });
    expect((await rewrittenPage(bytes, null, 0, [empty])).skipped).toBe(1);
  });

  it("deleting a paragraph removes exactly it (the preview's « paragraph being typed »)", async () => {
    const { bytes } = await open("chromium");
    const blocks = await blocksOf("chromium", 0);
    const b = blocks.find((x) => x.text.startsWith("Colonne gauche"))!;
    const t0 = performance.now();
    const r = await rewrittenPage(bytes, null, 0, [editOf(b, b.spans!, { deleted: true, text: "" })]);
    const ms = performance.now() - t0;
    const after = await lookAt(r.bytes);
    expect(NORM(after.text)).not.toContain(NORM("Colonne gauche"));
    for (const o of blocks) if (o !== b) expect(NORM(after.text)).toContain(NORM(o.text));
    expect(ms).toBeLessThan(400);
  });

  it("old edits (no spans) still work: the block's own font, colour and size", async () => {
    const { bytes } = await open("letter");
    const b = (await blocksOf("letter", 0)).find((x) => x.text.startsWith("Le présent"))!;
    const { spans: _s, indent: _i, ...old } = editOf(b, b.spans!, { text: "Le document décrit les parties." });
    void _s;
    void _i;
    const r = await rewrittenPage(bytes, null, 0, [old]);
    const out = (await lookAt(r.bytes)).blocks.find((x) => x.text.startsWith("Le document décrit les parties"))!;
    expect(out.spans![0].style.fontName).toBe(b.spans![0].style.fontName);
  });
});

